use typesake_core::english;

fn main() {
    for s in [
        "请发送报告",
        "太贵了",
        "我在开会",
        "我要买咖啡",
        "我们走吧",
        "我想喝茶",
        "我今天很忙",
        "明天开会",
        "我昨天买了书",
        "有没有空",
        "几点了",
        "这个多少钱",
        "我在学习英语",
        "你的项目进度怎么样",
        "谢谢你的支持",
        "能不能帮我确认一下",
        "祝你生日快乐",
        "我需要更多时间",
        "我们保持联系",
        "抱歉我迟到了",
        "我明天出差",
        "请稍等",
        "我需要帮助",
        "洗手间在哪里",
        "对不起",
        "我饿了",
    ] {
        let c = english::english_candidates(s);
        println!("{s} -> {c:?}");
    }
    println!("--- patterns ---");
    for s in ["请发送报告", "太贵了", "我在开会", "我要买咖啡", "我们走吧", "我想喝茶", "能不能帮我确认一下"] {
        println!("{s} -> {:?}", english::try_patterns(s));
    }
}
